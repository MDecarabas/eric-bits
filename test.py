#!/usr/bin/env python
"""Create assignment and configuration for the tiled catalog (for PSQL).

NOTE: Does NOT create the catalog databases and roles in PSQL.

Master registry file `assignments.yml` must exist.

- Creates credentials to use with PSQL
- Generates a database connection URI
- updates the `assignments.yml` file with the new catalog
- writes an init SQL (to configure PSQL for this catalog)
- writes a tiled config file
"""

# TODO:  Only if expanded to interact with PSQL server:
